// Lists the strings media/dashboard.js translates, so the extension can hand
// them to the page. Run: node scripts/dashboard-strings.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "media", "dashboard.js"), "utf8");
const keys = new Set();
for (const match of source.matchAll(/\bT\("((?:[^"\\]|\\.)+)"/g)) {
  keys.add(JSON.parse(`"${match[1]}"`));
}
for (const match of source.matchAll(/\bplural\([^,]+, "((?:[^"\\]|\\.)+)", "((?:[^"\\]|\\.)+)"\)/g)) {
  keys.add(JSON.parse(`"${match[1]}"`));
  keys.add(JSON.parse(`"${match[2]}"`));
}
const list = [...keys].sort((a, b) => a.localeCompare(b));
const body = list.map((key) => `    ${JSON.stringify(key)},`).join("\n");
const out = `// Generated by scripts/dashboard-strings.js from media/dashboard.js.\n// Do not edit by hand.\n\nexport const DASHBOARD_STRINGS: readonly string[] = [\n${body}\n];\n`;
fs.writeFileSync(path.join(root, "src", "webview", "dashboardStrings.ts"), out);
console.log(`${list.length} dashboard strings`);
